export const DEFAULT_THEME: ActiveTheme = 'void';

/** Apply a theme to the document via CSS custom properties */
export function applyTheme(theme: ThemeConfig): void {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  root.style.setProperty('--theme-bg', theme.bgGradient);
  root.style.setProperty('--theme-primary', theme.primaryColor);
  root.style.setProperty('--theme-secondary', theme.secondaryColor);
  root.style.setProperty('--theme-accent', theme.accentColor);
  root.style.setProperty('--theme-text', theme.textColor);
  root.style.setProperty('--theme-subtext', theme.subtextColor);
  root.style.setProperty('--theme-card-bg', theme.cardBg);
  root.style.setProperty('--theme-card-border', theme.cardBorder);
  root.style.setProperty('--theme-particle', theme.particleColor);
  root.style.setProperty('--theme-glow', theme.glowColor);
  root.style.setProperty('--theme-cursor', theme.cursorColor);
}
