/** Return all spells for an element that match a given trigger. */
export function getSpellsForTrigger(element: ElementType, trigger: SpellTrigger): SpellDef[] {
  return (ELEMENT_SPELLS[element] ?? []).filter((s) => s.triggers.includes(trigger));
}
