/**
 * magicSystem.ts
 * Defines the elemental magic spell system for all 14 spirit types.
 *
 * Each element has 3 signature spells triggered by different events:
 *  - speaking  : cast when spirit begins talking
 *  - tap       : cast when user clicks the spirit
 *  - hover     : cast on hover-enter
 *  - idle      : periodic ambient cast (background magic)
 *  - excited / angry / happy / sad / ... : emotional reactive casts
 *
 * Spells are safe by design — particles fade before reaching 130px
 * from the spirit center, never covering important UI content.
 */

import { ElementType, EmotionType } from '../types/spirit.types';

// ── Types ─────────────────────────────────────────────────────────

export type ParticleShape = 'circle' | 'diamond' | 'leaf' | 'bolt' | 'square' | 'ring';

export type SpellTrajectory =
  | 'explode'    // 360° radial burst
  | 'burst-up'   // upper hemisphere burst
  | 'rise'       // float straight upward
  | 'rain'       // fall downward
  | 'spiral'     // outward spiral path
  | 'orbit';     // expand to ring radius then fade

export type SpellTrigger =
  | 'speaking'
  | 'hover'
  | 'tap'
  | 'idle'
  | 'excited'
  | 'angry'
  | 'happy'
  | 'sad'
  | 'surprised'
  | 'mysterious'
  | 'calm'
  | 'proud';

export interface SpellDef {
  id: string;
  name: string;
  /** Number of simultaneous particles */
  particleCount: number;
  shape: ParticleShape;
  colors: string[];
  trajectory: SpellTrajectory;
  /** Max travel distance in CSS px from spirit center */
  speedPx: number;
  /** [min, max] individual particle size in CSS px */
  sizePx: [number, number];
  /** Total animation duration in ms */
  durationMs: number;
  /** CSS box-shadow glow color — undefined = no glow */
  glowColor?: string;
  /** Which state changes fire this spell */
  triggers: SpellTrigger[];
  /** Minimum ms between consecutive idle casts of this spell */
  idleCooldownMs?: number;
}

